#!/usr/bin/env python3
# HeyHi Confidential — Wheelhouse (sheerline/studio) internal link checker.
# classification: confidential
#
# Static check that every INTERNAL href/src in the studio HTML resolves to a
# real file on disk (the plan §10 AC-3 mechanism, and D-08 smoke test 2). It is
# read-only and dependency-free (python3 stdlib only).
#
# What it verifies (hard, exit 1 on any failure):
#   - every relative href="…"/src="…" file path exists, resolved from the file's
#     own directory (external http/https/mailto/tel/data/js URLs are skipped).
# What it reports but never fails on:
#   - in-page and cross-page "#anchor" targets. Many studio anchors (#area-<key>
#     on areas.html, #cap-<id> on skills.html) are generated at render time by
#     inline JS, so a static id sweep cannot see them; they are listed with a
#     static-hit / render-time note for the human, not treated as broken.

import os
import re
import sys

STUDIO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HREF_SRC = re.compile(r'(?:href|src)\s*=\s*"([^"]*)"')
ID_ATTR = re.compile(r'\bid\s*=\s*"([^"]+)"')
SKIP_PREFIXES = ("http://", "https://", "mailto:", "tel:", "data:", "javascript:", "//")


def html_files():
    return sorted(
        f for f in os.listdir(STUDIO)
        if f.endswith(".html") and os.path.isfile(os.path.join(STUDIO, f))
    )


def static_ids(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return set(ID_ATTR.findall(fh.read()))
    except OSError:
        return set()


def main():
    file_failures = []
    anchor_notes = []
    checked_files = 0
    checked_anchors = 0

    for name in html_files():
        path = os.path.join(STUDIO, name)
        with open(path, encoding="utf-8") as fh:
            refs = HREF_SRC.findall(fh.read())
        for ref in refs:
            ref = ref.strip()
            if not ref or ref.startswith("#"):
                # pure in-page anchor — record, do not fail (may be JS-generated)
                if ref.startswith("#") and len(ref) > 1:
                    checked_anchors += 1
                    frag = ref[1:]
                    hit = frag in static_ids(path)
                    anchor_notes.append(
                        f"  {name} -> {ref}  [{'static id' if hit else 'render-time id?'}]"
                    )
                continue
            if ref.startswith(SKIP_PREFIXES):
                continue
            filepart, _, frag = ref.partition("#")
            if not filepart:
                continue
            target = os.path.normpath(os.path.join(STUDIO, filepart))
            checked_files += 1
            if not os.path.exists(target):
                file_failures.append(f"  {name} -> {ref}  (missing: {filepart})")
            elif frag:
                checked_anchors += 1
                hit = frag in static_ids(target)
                anchor_notes.append(
                    f"  {name} -> {ref}  [{'static id' if hit else 'render-time id?'}]"
                )

    print(f"link-check over {len(html_files())} studio HTML files")
    print(f"  internal file refs checked : {checked_files}")
    print(f"  anchor refs recorded       : {checked_anchors}")

    if anchor_notes:
        print("\nanchors (informational — render-time ids are generated by inline JS):")
        for line in anchor_notes:
            print(line)

    if file_failures:
        print(f"\nFAIL — {len(file_failures)} unresolved internal file ref(s):")
        for line in file_failures:
            print(line)
        return 1

    print("\nOK — every internal file href/src resolves.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

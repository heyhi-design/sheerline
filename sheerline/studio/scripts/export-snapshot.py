#!/usr/bin/env python3
# classification: confidential
# HeyHi Confidential
#
# Sheerline Studio — snapshot exporter (DISPATCH-01).
#
# Reads the live sheerline/ tree READ-ONLY and emits sheerline/studio/data/snapshot.js,
# the single truth layer every Studio screen renders from. It never writes, touches, or
# reorders any source file; the only path it writes is sheerline/studio/data/snapshot.js.
#
# Authoritative output contract: plans/plan-sheerline-studio-ui-2026-08-21.md § 6.2.
# Emits exactly:  window.SHEERLINE_DATA = <json>;  with 11 top-level keys:
#   meta, areas, phases, early_warning_signals, capabilities, corrections,
#   seminar, dispatch, intake, decisions, artifacts.
#
# Determinism: re-running at the same HEAD produces a byte-identical file. `generated_at`
# is the HEAD commit's committer date (not wall-clock) precisely so the output is
# reproducible; glob-derived lists are explicitly sorted; source field order is preserved
# (PyYAML keeps mapping order; json.dumps is called without sort_keys).
#
# Assertions run in BOTH modes (never only with --check) and fail loudly (nonzero exit +
# a named assertion) BEFORE anything is written, so a partial snapshot is never emitted.
#   --check : build everything, run every assertion, print the counts, write nothing.
#
# Dependencies: python3 stdlib + PyYAML (both already used by repo scripts). No network,
# no pip installs, no node (the emitted file assigns a window global, so it is not
# require()-able; --check validates the round-trip in-process instead).

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

EXPORTER_VERSION = "1.0.0"

# ── Path anchors, resolved from this file so the exporter is CWD-independent ──────────
SCRIPT = Path(__file__).resolve()
STUDIO_DIR = SCRIPT.parent.parent            # sheerline/studio
SHEERLINE_DIR = STUDIO_DIR.parent            # sheerline
REPO_ROOT = SHEERLINE_DIR.parent             # repo root (git runs here; artifact paths are relative to it)
DATA_DIR = STUDIO_DIR / "data"
OUT_FILE = DATA_DIR / "snapshot.js"

GENERATED_HEADER = "// GENERATED by scripts/export-snapshot.py — do not hand-edit."
ASSIGN_PREFIX = "window.SHEERLINE_DATA = "

# Source files (all under sheerline/, except the dispatch batches which live at repo root).
SRC = {
    "registry": SHEERLINE_DIR / "os" / "foundations" / "registry.yaml",
    "project_state": SHEERLINE_DIR / "os" / "project-state.yaml",
    "skill_registry": SHEERLINE_DIR / "skills" / "registry" / "skill-registry.yaml",
    "seed_corrections": SHEERLINE_DIR / "os" / "corrections" / "seed-corrections.yaml",
    "seminar_readme": SHEERLINE_DIR / "seminar" / "README.md",
    "intake": SHEERLINE_DIR / "profile" / "engagement-intake.yaml",
    "decision_log": SHEERLINE_DIR / "os" / "decision-log.md",
}


class ExportError(Exception):
    """A named, loud failure. The message identifies the assertion that failed."""


def fail(msg: str):
    raise ExportError(msg)


# ── Small IO / parsing helpers ────────────────────────────────────────────────────────

def read_text(path: Path) -> str:
    if not path.exists():
        fail(f"source missing: {path}")
    return path.read_text(encoding="utf-8")


def load_yaml(path: Path):
    import yaml
    return yaml.safe_load(read_text(path))


def git(*args: str) -> str:
    """Run git in the repo root; fail loudly if it errors (meta.source_commit needs it)."""
    try:
        out = subprocess.run(
            ["git", *args],
            cwd=str(REPO_ROOT),
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        fail(f"git {' '.join(args)} failed: {exc}")
    return out.stdout.strip()


def import_yaml_frontmatter(text: str) -> dict:
    """Parse a leading --- ... --- YAML frontmatter block. {} if absent."""
    import yaml
    m = re.match(r"^---\n(.*?)\n---\n", text, flags=re.S)
    if not m:
        return {}
    parsed = yaml.safe_load(m.group(1))
    return parsed if isinstance(parsed, dict) else {}


# ── Per-key builders ──────────────────────────────────────────────────────────────────

def build_meta() -> dict:
    # generated_at is the SOURCE COMMIT's committer date (ISO 8601), not wall-clock, so the
    # exporter is deterministic: same HEAD -> byte-identical output (plan § 6.2 determinism).
    return {
        # An exported copy has no git history: the export passes the source commit and its
        # date through these two variables instead, keeping the snapshot deterministic.
        "generated_at": os.environ.get("SHEERLINE_SNAPSHOT_DATE") or git("show", "-s", "--format=%cI", "HEAD"),
        "source_commit": os.environ.get("SHEERLINE_SNAPSHOT_COMMIT") or git("rev-parse", "--short", "HEAD"),
        "exporter_version": EXPORTER_VERSION,
    }


def build_areas() -> list:
    """Every field of each entry in os/foundations/registry.yaml `areas:`, verbatim."""
    data = load_yaml(SRC["registry"])
    areas = data.get("areas")
    if not isinstance(areas, list):
        fail("registry.yaml has no `areas:` list")
    return areas


def build_phases() -> list:
    """os/project-state.yaml `phases:` verbatim."""
    data = load_yaml(SRC["project_state"])
    phases = data.get("phases")
    if not isinstance(phases, list):
        fail("project-state.yaml has no `phases:` list")
    return phases


def build_early_warning_signals() -> list:
    """Projection to exactly {id, description, current_status, last_checked} per § 6.2
    (threshold and action are intentionally NOT carried)."""
    data = load_yaml(SRC["project_state"])
    signals = data.get("early_warning_signals")
    if not isinstance(signals, list):
        fail("project-state.yaml has no `early_warning_signals:` list")
    fields = ["id", "description", "current_status", "last_checked"]
    return [{k: sig.get(k) for k in fields} for sig in signals]


def build_capabilities() -> dict:
    """{ meta: {version, skills, references, total_capabilities}, entries: [verbatim] }."""
    data = load_yaml(SRC["skill_registry"])
    meta = data.get("meta") or {}
    entries = data.get("capabilities")
    if not isinstance(entries, list):
        fail("skill-registry.yaml has no `capabilities:` list")
    proj_meta = {k: meta.get(k) for k in ("version", "skills", "references", "total_capabilities")}
    return {"meta": proj_meta, "entries": entries}


def build_corrections() -> list:
    """entries of os/corrections/seed-corrections.yaml, fields carried as-is (null stays null)."""
    data = load_yaml(SRC["seed_corrections"])
    entries = data.get("entries")
    if not isinstance(entries, list):
        fail("seed-corrections.yaml has no `entries:` list")
    return entries


def _module_sort_key(path: Path):
    # module-<track>-<n>.md -> (track, n) as ints for natural ordering.
    m = re.match(r"module-(\d+)-(\d+)\.md$", path.name)
    return (int(m.group(1)), int(m.group(2))) if m else (9999, path.name)


def _track_titles_from_readme() -> dict:
    """Parse the curriculum-map table; return {track_number: title}. Join key is the leading
    digit of each row's first cell (`**0 · Orientation**` -> 0)."""
    text = read_text(SRC["seminar_readme"])
    titles = {}
    in_table = False
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("| Track") and "Modules" in s:
            in_table = True
            continue
        if in_table:
            if not s.startswith("|"):
                break  # table ended
            if re.match(r"^\|[\s:-]+\|", s):
                continue  # separator row
            cells = [c.strip() for c in s.split("|")]
            # cells[0] is '' (leading pipe); cells[1] is the Track cell.
            if len(cells) < 2:
                continue
            title = re.sub(r"\*\*", "", cells[1]).strip()
            nm = re.match(r"(\d+)", title)
            if nm:
                titles[int(nm.group(1))] = title
    return titles


def build_seminar() -> dict:
    """{ tracks: [ { dir, title, modules: [ { file, title, teaches } ] } ] } — track titles
    from the README curriculum map, module title/teaches from each module's frontmatter."""
    track_titles = _track_titles_from_readme()
    track_dirs = sorted(
        (p for p in (SHEERLINE_DIR / "seminar").glob("track-*") if p.is_dir()),
        key=lambda p: int(re.match(r"track-(\d+)-", p.name).group(1))
        if re.match(r"track-(\d+)-", p.name) else 9999,
    )
    tracks = []
    for tdir in track_dirs:
        tm = re.match(r"track-(\d+)-", tdir.name)
        if not tm:
            fail(f"unexpected track dir name: {tdir.name}")
        tnum = int(tm.group(1))
        if tnum not in track_titles:
            fail(f"no curriculum-map title for track {tnum} ({tdir.name}) in seminar/README.md")
        modules = []
        for mpath in sorted(tdir.glob("module-*.md"), key=_module_sort_key):
            fm = import_yaml_frontmatter(read_text(mpath))
            if "title" not in fm or "teaches" not in fm:
                fail(f"module missing title/teaches frontmatter: {mpath}")
            modules.append({"file": mpath.name, "title": fm["title"], "teaches": fm["teaches"]})
        tracks.append({"dir": tdir.name, "title": track_titles[tnum], "modules": modules})
    return {"tracks": tracks}


def _frontmatter_status(text: str):
    """Return the YAML-parsed `status` value from a doc's frontmatter. Parsing as YAML is the
    'verbatim from frontmatter' reading: a quoted annotated string is carried in full, while a
    ` # ...` annotation (a YAML comment) is correctly not part of the value."""
    fm = import_yaml_frontmatter(text)
    return fm.get("status")


_DISPATCH_HEADER = re.compile(r"^#{1,2}\s+(DISPATCH-[A-Za-z0-9]+)\s*(?:[—–:]\s*)?(.*?)\s*$")


def build_dispatch() -> dict:
    """{ batches: [ { file, status, example, prompts: [ { id, title } ] } ] } — glob Sheerline's
    own batch folder (os/dispatch/batches/; it ships two worked examples, flagged `example`);
    status verbatim from frontmatter; prompts from ^#{1,2} DISPATCH- headers (batches mix h1 and
    h2, and use either ' — ' or ': ' between id and title). Reads only inside sheerline/, never
    an instance's own dispatch history."""
    batch_paths = sorted((SHEERLINE_DIR / "os" / "dispatch" / "batches").glob("dispatch-prompts-*.md"))
    if not batch_paths:
        fail("no dispatch batches matched os/dispatch/batches/dispatch-prompts-*.md")
    batches = []
    for bp in batch_paths:
        text = read_text(bp)
        prompts = []
        for line in text.splitlines():
            m = _DISPATCH_HEADER.match(line)
            if m:
                prompts.append({"id": m.group(1), "title": m.group(2).strip()})
        batches.append({
            "file": bp.name,
            "status": _frontmatter_status(text),
            "example": bool(import_yaml_frontmatter(text).get("example")),
            "prompts": prompts,
        })
    return {"batches": batches}


def _inline_comment(line: str):
    """The text of a YAML inline comment (a `#` preceded by whitespace), or None."""
    m = re.search(r"\s#\s?(.*)$", line)
    return m.group(1).strip() if m else None


def _field_comment(body_lines: list, key: str) -> str:
    """Trailing comment for `key` within a section's raw line span: the inline comment if
    present, else the joined block of comment-only lines that immediately follow (which is how
    practice_areas_in_scope carries its [6, 7, 8] example)."""
    pat = re.compile(rf"^\s*{re.escape(key)}\s*:")
    for i, line in enumerate(body_lines):
        if pat.match(line):
            inline = _inline_comment(line)
            if inline is not None:
                return inline
            collected = []
            for nxt in body_lines[i + 1:]:
                s = nxt.strip()
                if s.startswith("#"):
                    collected.append(s.lstrip("#").strip())
                else:
                    break
            return " ".join(collected)
    return ""


def build_intake() -> dict:
    """{ sections: [ { name, fields: [ { key, comment } ] } ] } — keys + trailing comments,
    values omitted. Sections are the mapping-valued top-level keys, plus practice_areas_in_scope
    (a bare list) modeled as a section with a single list-typed field (§ 6.2). The scalar
    top-level `classification:` mark is document metadata, not an intake field, so it is not a
    section. [judgment]"""
    text = read_text(SRC["intake"])
    lines = text.splitlines()
    data = load_yaml(SRC["intake"])  # order-preserving top-level mapping

    # Line index of each top-level key (column 0) so we can bound each section's raw span.
    top_line = {}
    for i, line in enumerate(lines):
        m = re.match(r"^([A-Za-z_][\w-]*):", line)
        if m and m.group(1) in data:
            top_line.setdefault(m.group(1), i)

    def body_span(key: str) -> list:
        start = top_line[key]
        later = [ln for ln in top_line.values() if ln > start]
        end = min(later) if later else len(lines)
        return lines[start:end]

    sections = []
    for key, val in data.items():
        if isinstance(val, dict):
            body = body_span(key)
            fields = [{"key": sk, "comment": _field_comment(body, sk)} for sk in val.keys()]
            sections.append({"name": key, "fields": fields})
        elif isinstance(val, list):
            # bare top-level list -> a section with one list-typed field named after the key.
            body = body_span(key)
            sections.append({"name": key, "fields": [{"key": key, "comment": _field_comment(body, key)}]})
        # scalars (classification) are not intake sections — skipped.
    return {"sections": sections}


_DECISION_HEADER = re.compile(r"^##\s+(\d{4}-\d{2}-\d{2})\s*-\s*(.*)$")


def build_decisions() -> list:
    """[ { date, title } ] from os/decision-log.md entry headers (only ^## YYYY-MM-DD, so the
    structural `## The rules` / `## Entries` headers are excluded)."""
    text = read_text(SRC["decision_log"])
    decisions = []
    for line in text.splitlines():
        m = _DECISION_HEADER.match(line)
        if m:
            decisions.append({"date": m.group(1), "title": m.group(2).strip()})
    return decisions


# artifacts: (glob, kind), in the contract's listed order. Paths are repo-relative.
ARTIFACT_GLOBS = [
    ("docs/diagrams/*.svg", "diagram"),
    ("seminar/track-*/module-*.md", "seminar-module"),
    ("skills/evals/*/cases.yaml", "eval-cases"),
    ("os/corrections/seed-corrections.yaml", "correction-seeds"),
    ("profile/engagement-intake.yaml", "template"),
    ("profile/intake-conversation.md", "template"),
]


def build_artifacts() -> list:
    """[ { path, kind, name } ] derived by glob; path is repo-relative POSIX; name is the
    basename. Sorted within each kind for determinism."""
    artifacts = []
    for pattern, kind in ARTIFACT_GLOBS:
        for p in sorted(SHEERLINE_DIR.glob(pattern)):
            artifacts.append({
                "path": p.resolve().relative_to(REPO_ROOT).as_posix(),
                "kind": kind,
                "name": p.name,
            })
    return artifacts


# ── Assemble + assert ─────────────────────────────────────────────────────────────────

def build_snapshot() -> dict:
    return {
        "meta": build_meta(),
        "areas": build_areas(),
        "phases": build_phases(),
        "early_warning_signals": build_early_warning_signals(),
        "capabilities": build_capabilities(),
        "corrections": build_corrections(),
        "seminar": build_seminar(),
        "dispatch": build_dispatch(),
        "intake": build_intake(),
        "decisions": build_decisions(),
        "artifacts": build_artifacts(),
    }


def emit_content(data: dict) -> str:
    """The exact bytes written to snapshot.js: a // header comment, then the window global."""
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return f"{GENERATED_HEADER}\n{ASSIGN_PREFIX}{body};\n"


def run_assertions(data: dict) -> None:
    """Every assertion runs in both modes and fails loudly. Named so a failure points at itself."""
    # 1. All 11 top-level keys present.
    expected_keys = [
        "meta", "areas", "phases", "early_warning_signals", "capabilities",
        "corrections", "seminar", "dispatch", "intake", "decisions", "artifacts",
    ]
    missing = [k for k in expected_keys if k not in data]
    if missing:
        fail(f"[keys] missing top-level keys: {missing}")

    # 2. capabilities.meta counts match parsed entry counts.
    cap = data["capabilities"]
    entries = cap["entries"]
    cmeta = cap["meta"]
    n_ref = sum(1 for e in entries if e.get("type") == "reference")
    n_skill = sum(1 for e in entries if e.get("type") == "skill")
    if cmeta.get("total_capabilities") != len(entries):
        fail(f"[capabilities.total] meta.total_capabilities={cmeta.get('total_capabilities')} != {len(entries)} entries")
    if cmeta.get("references") != n_ref:
        fail(f"[capabilities.references] meta.references={cmeta.get('references')} != {n_ref} type=reference entries")
    if cmeta.get("skills") != n_skill:
        fail(f"[capabilities.skills] meta.skills={cmeta.get('skills')} != {n_skill} type=skill entries")

    # 3. areas length == count of `- id:` entries in the raw registry file.
    raw_id_count = len(re.findall(r"^\s*-\s+id:", read_text(SRC["registry"]), flags=re.M))
    if len(data["areas"]) != raw_id_count:
        fail(f"[areas] parsed {len(data['areas'])} areas != {raw_id_count} `- id:` lines in registry.yaml")

    # 4. Every globbed dispatch batch yields >= 1 prompt (an empty list means the header regex missed).
    for b in data["dispatch"]["batches"]:
        if len(b["prompts"]) < 1:
            fail(f"[dispatch] batch {b['file']} yielded 0 prompts (header regex missed)")

    # 5. Every artifacts[].path exists on disk.
    for a in data["artifacts"]:
        if not (REPO_ROOT / a["path"]).exists():
            fail(f"[artifacts] path does not exist: {a['path']}")

    # 6. The emitted JSON round-trips through json.loads via the same strip used by the smoke test.
    content = emit_content(data)
    stripped = re.sub(r"^//.*$|^window\.SHEERLINE_DATA = |;\s*$", "", content.strip(), flags=re.M)
    try:
        reparsed = json.loads(stripped)
    except json.JSONDecodeError as exc:
        fail(f"[roundtrip] emitted content is not valid JSON after strip: {exc}")
    if reparsed != data:
        fail("[roundtrip] reparsed JSON does not equal the source data")


def summarize(data: dict) -> str:
    cap = data["capabilities"]["meta"]
    n_modules = sum(len(t["modules"]) for t in data["seminar"]["tracks"])
    n_prompts = sum(len(b["prompts"]) for b in data["dispatch"]["batches"])
    n_fields = sum(len(s["fields"]) for s in data["intake"]["sections"])
    kinds = {}
    for a in data["artifacts"]:
        kinds[a["kind"]] = kinds.get(a["kind"], 0) + 1
    kind_str = ", ".join(f"{k}={v}" for k, v in sorted(kinds.items()))
    lines = [
        f"  source_commit        : {data['meta']['source_commit']}  ({data['meta']['generated_at']})",
        f"  areas                : {len(data['areas'])}",
        f"  phases               : {len(data['phases'])}",
        f"  early_warning_signals: {len(data['early_warning_signals'])}",
        f"  capabilities         : total={cap['total_capabilities']} skills={cap['skills']} references={cap['references']} (entries={len(data['capabilities']['entries'])})",
        f"  corrections          : {len(data['corrections'])}",
        f"  seminar              : tracks={len(data['seminar']['tracks'])} modules={n_modules}",
        f"  dispatch             : batches={len(data['dispatch']['batches'])} prompts={n_prompts}",
        f"  intake               : sections={len(data['intake']['sections'])} fields={n_fields}",
        f"  decisions            : {len(data['decisions'])}",
        f"  artifacts            : {len(data['artifacts'])}  ({kind_str})",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Export the Sheerline Studio data snapshot (read-only over sheerline/).")
    ap.add_argument("--check", action="store_true",
                    help="build everything, run every assertion, print the counts, write nothing")
    args = ap.parse_args()

    try:
        data = build_snapshot()
        run_assertions(data)
    except ExportError as exc:
        print(f"EXPORT FAILED — {exc}", file=sys.stderr)
        return 1

    print(summarize(data))

    if args.check:
        print("CHECK OK — assertions passed, no file written.")
        return 0

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(emit_content(data), encoding="utf-8")
    print(f"WROTE {OUT_FILE.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

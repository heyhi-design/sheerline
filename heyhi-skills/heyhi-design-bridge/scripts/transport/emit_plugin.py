#!/usr/bin/env python3
"""
HeyHi Design Bridge — Plugin Emitter (the non-agent-transcription transport).

`use_figma` takes inline `code` only and its sandbox has no network (fetch/XHR are
undefined), so the agent cannot get a ~44k chunk into it without re-typing it — the
documented transcription failure (dense SVG masters silently dropped). A Figma dev
plugin is the fix, but the plugin main thread also blocks `eval`/`new Function`, so
fetch-then-eval is out too. The robust path: **bundle** each chunk as a real async
function into a generated `code.js`. No eval, no network — and each chunk runs in
its own function scope, which exactly replicates `use_figma`'s per-call semantics
(fresh `made`/`out`, ids threaded via the `IDMAP` parameter).

This reads a `build_figma.py --out-dir` (manifest.json + chunk_<i>.js + any raster
assets) and assembles a self-contained, runnable plugin dir:

    <plugin-out>/manifest.json   (copied; networkAccess "none")
    <plugin-out>/ui.html         (copied; a Build button + result readout)
    <plugin-out>/code.js         (GENERATED: chunks as functions + idmap loop + rasters)

The chunk transform: each raw `chunk_<i>.js` begins `const IDMAP = __IDMAP__;`. We
drop that line (IDMAP becomes the function parameter) and wrap the rest as
`async function __chunk_<i>(IDMAP) { ... return JSON.stringify(out); }`. The runner
loop calls them in order, merging each return's created/reused ids into a single
in-memory idmap (no 50k cap inside a plugin, so the full map threads — the prep-time
pruning that the cap forced is unnecessary here). Raster IMAGE fills (the v0.8.0
post-write `upload_assets` manifest) are embedded by the plugin itself via
`figma.createImage`, bytes bundled as base64 — same end state, one self-contained run.

IMPORTANT: the generated code.js embeds the build's chunk + raster data. For a client
build that is client-confidential — write <plugin-out> to a gitignored runtime path,
never commit it. The static manifest.json / ui.html carry no build data.

Usage:
    python3 emit_plugin.py --out-dir <build-dir> --plugin-out <runnable-plugin-dir>

HeyHi Confidential.
"""
import argparse
import base64
import json
import os
import re
import shutil

IDMAP_DECL = "const IDMAP = __IDMAP__;"

# --- static runner scaffold (no eval, no network) --------------------------------
SCAFFOLD_HEAD = r"""// GENERATED by emit_plugin.py — HeyHi Design Bridge plugin runner. Do NOT commit
// (build chunk + raster data is embedded; for a client build that is confidential).
figma.showUI(__html__, { width: 480, height: 420 });

// Pure-JS base64 -> Uint8Array (figma main thread has no atob); prefers the API helper.
function __b64ToBytes(b64) {
  if (typeof figma.base64Decode === 'function') return figma.base64Decode(b64);
  var chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  var lookup = {}; for (var i = 0; i < chars.length; i++) lookup[chars[i]] = i;
  var clean = b64.replace(/[^A-Za-z0-9+/]/g, '');
  var out = []; var n = clean.length;
  for (var j = 0; j < n; j += 4) {
    var e0 = lookup[clean[j]], e1 = lookup[clean[j + 1]];
    var e2 = lookup[clean[j + 2]], e3 = lookup[clean[j + 3]];
    out.push((e0 << 2) | (e1 >> 4));
    if (clean[j + 2] !== undefined) out.push(((e1 & 15) << 4) | (e2 >> 2));
    if (clean[j + 3] !== undefined) out.push(((e2 & 3) << 6) | e3);
  }
  return new Uint8Array(out);
}
"""

SCAFFOLD_RUN = r"""
async function __runBuild() {
  const idmap = {};
  const summary = { created: 0, reused: 0, flags: [], errors: [], pages: [], rasters: 0 };
  for (let i = 0; i < __CHUNKS__.length; i++) {
    figma.ui.postMessage({ type: 'progress', text: 'chunk ' + (i + 1) + ' / ' + __CHUNKS__.length + ' …' });
    let r;
    try { r = JSON.parse(await __CHUNKS__[i](idmap)); }
    catch (e) { summary.errors.push({ chunk: i, error: String((e && e.message) || e) }); continue; }
    Object.assign(idmap, r.created || {}, r.reused || {});
    summary.created += Object.keys(r.created || {}).length;
    summary.reused += Object.keys(r.reused || {}).length;
    (r.flags || []).forEach((f) => summary.flags.push(f));
    (r.errors || []).forEach((e) => summary.errors.push(e));
    if (r.pageId && summary.pages.indexOf(r.pageId) < 0) summary.pages.push(r.pageId);
    if (r.pageId) { try { const p = await figma.getNodeByIdAsync(r.pageId); if (p) await figma.setCurrentPageAsync(p); } catch (e) {} }
  }
  for (const a of __ASSETS__) {
    const nid = idmap[a.key];
    if (!nid) { summary.errors.push({ asset: a.key, error: 'node id missing for raster' }); continue; }
    try {
      const img = figma.createImage(__b64ToBytes(a.b64));
      const node = await figma.getNodeByIdAsync(nid);
      if (!node) { summary.errors.push({ asset: a.key, error: 'raster node not found' }); continue; }
      node.fills = [{ type: 'IMAGE', scaleMode: a.scaleMode || 'FILL', imageHash: img.hash }];
      summary.rasters++;
    } catch (e) { summary.errors.push({ asset: a.key, error: String((e && e.message) || e) }); }
  }
  figma.notify('HeyHi Bridge: ' + summary.created + ' nodes, ' + summary.rasters + ' raster(s), ' + summary.errors.length + ' error(s)');
  figma.ui.postMessage({ type: 'summary', summary });
}
figma.ui.onmessage = async (msg) => {
  if (msg && msg.type === 'run') {
    try { await __runBuild(); }
    catch (e) { figma.ui.postMessage({ type: 'summary', summary: { created: 0, reused: 0, flags: [], errors: [{ fatal: String((e && e.message) || e) }], pages: [], rasters: 0 } }); }
  }
};
"""


def wrap_chunk(i, raw):
    if IDMAP_DECL not in raw:
        raise SystemExit("chunk_%d.js missing the '%s' line — chunk format changed?" % (i, IDMAP_DECL))
    body = raw.replace(IDMAP_DECL, "// IDMAP is the function parameter", 1)
    return "async function __chunk_%d(IDMAP) {\n%s\n}\n" % (i, body)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description="Emit a self-contained HeyHi Design Bridge runner plugin")
    ap.add_argument("--out-dir", required=True, help="a build_figma.py --out-dir (manifest.json + chunk_*.js)")
    ap.add_argument("--plugin-out", required=True, help="dir to assemble the runnable plugin into (gitignored for client builds)")
    args = ap.parse_args()
    out_dir = os.path.abspath(args.out_dir)
    plugin_out = os.path.abspath(args.plugin_out)

    man = json.load(open(os.path.join(out_dir, "manifest.json"), encoding="utf-8"))
    n = man.get("chunk_count", 0)
    page_name = man.get("page_name", "(unknown)")

    parts = [SCAFFOLD_HEAD]
    for i in range(n):
        cf = os.path.join(out_dir, "chunk_%d.js" % i)
        parts.append(wrap_chunk(i, open(cf, encoding="utf-8").read()))
    parts.append("const __CHUNKS__ = [%s];\n" % ", ".join("__chunk_%d" % i for i in range(n)))

    assets_js = []
    total_raster_bytes = 0
    for a in man.get("assets", []):
        ref = a.get("imageRef")
        if not ref or not os.path.isfile(ref):
            assets_js.append({"key": a.get("key"), "scaleMode": a.get("scaleMode", "FILL"), "b64": "", "missing": True})
            continue
        data = open(ref, "rb").read()
        total_raster_bytes += len(data)
        assets_js.append({"key": a.get("key"), "scaleMode": a.get("scaleMode", "FILL"),
                          "b64": base64.b64encode(data).decode("ascii")})
    parts.append("const __ASSETS__ = %s;\n" % json.dumps(assets_js, ensure_ascii=False))

    meta_line = "%s\\n%d chunk(s), %d raster(s) bundled. Click Build to write into the open file." % (
        page_name.replace('"', '\\"'), n, len(assets_js))
    parts.append('figma.ui.postMessage({ type: "meta", text: "%s" });\n' % meta_line)
    parts.append(SCAFFOLD_RUN)

    os.makedirs(plugin_out, exist_ok=True)
    code_js = "\n".join(parts)
    with open(os.path.join(plugin_out, "code.js"), "w", encoding="utf-8") as fh:
        fh.write(code_js)
    # Per-build unique manifest id + name. Figma keys dev plugins by manifest `id`, so a
    # shared id collapses two builds into one registration (a real collision: importing a
    # second build silently runs the first). Derive a distinct id from the plugin-out dir
    # and a self-labeling name from the page, so every build is unambiguous in the menu.
    plugin_slug = re.sub(r"[^a-z0-9]+", "-", os.path.basename(plugin_out).lower()).strip("-") or "build"
    manifest = {
        "name": "HeyHi Bridge Runner — " + page_name,
        "id": "heyhi-design-bridge-runner-" + plugin_slug,
        "api": "1.0.0",
        "main": "code.js",
        "ui": "ui.html",
        "editorType": ["figma"],
        "networkAccess": {
            "allowedDomains": ["none"],
            "reasoning": "Self-contained: the build chunks and raster bytes are bundled into code.js by emit_plugin.py. No network access is needed.",
        },
    }
    with open(os.path.join(plugin_out, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")
    shutil.copy(os.path.join(here, "plugin", "ui.html"), os.path.join(plugin_out, "ui.html"))

    print("HeyHi Design Bridge plugin assembled")
    print("  plugin name : %s" % manifest["name"])
    print("  plugin id   : %s" % manifest["id"])
    print("  page        : %s" % page_name)
    print("  chunks      : %d   rasters: %d (%d KB)" % (n, len(assets_js), total_raster_bytes // 1024))
    print("  code.js size: %d KB" % (len(code_js.encode("utf-8")) // 1024))
    print("  plugin dir  : %s" % plugin_out)
    print("  import this manifest in Figma: Plugins > Development > Import plugin from manifest…")


if __name__ == "__main__":
    main()
